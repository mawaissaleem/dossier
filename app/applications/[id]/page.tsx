import { Suspense } from "react";
import { notFound } from "next/navigation";
import { connection } from "next/server";
import { getApplicationDetail } from "@/lib/db/applications";
import { listApplicationFiles } from "@/lib/db/files";
import { getFileLabels, getFilesRoot } from "@/lib/db/settings";
import { CheckIcon } from "lucide-react";
import { Page } from "@/components/page-header";
import { ApplicationActions } from "./application-actions";
import { EditApplication } from "./edit-application";
import { AddNote } from "./add-note";
import { FileList } from "./file-list";
import { FileUpload } from "./file-upload";
import { NewSubmission } from "./new-submission";
import { NoteList } from "./note-list";
import { SubmissionTimeline } from "./submission-timeline";
import { EmptyState } from "@/components/empty-state";
import { listNotes } from "@/lib/db/notes";
import { listSubmissions } from "@/lib/db/submissions";
import { linkLabel, safeHref } from "@/lib/cells";
import { formatCell } from "@/lib/table";
import { OptionChip } from "@/app/option-chip";
import { findOption } from "@/lib/options";

// The New submission button is always in the heading row, never inside the empty state: it stays mounted when the first submission arrives, so focus and "Submission saved." survive the refresh.
// Submissions sit above the fields (inside the view-mode children) so the latest one is on screen without scrolling (AT-12).
// Same pattern as the track page: request-time work inside Suspense. Unknown ids render the 404 page but with status 200
// (tested: also without Suspense and without the layout's nav boundary; a real 404 needs a Proxy lookup, see the 1.10 report).
// Typed by hand like the track page (PageProps<> is generated by `next build`).
async function ApplicationView({ params }: { params: Promise<{ id: string }> }) {
  await connection();
  const { id: raw } = await params;
  const detail = /^\d+$/.test(raw) ? await getApplicationDetail(Number(raw)) : null;
  if (!detail) notFound();
  const [root, labels, files, subs, notes] = await Promise.all([getFilesRoot(), getFileLabels(), listApplicationFiles(detail.id), listSubmissions(detail.id), listNotes(detail.id)]);
  const statusCol = detail.columns.find((c) => c.isStatus);
  const status = statusCol ? { columnId: statusCol.id, name: statusCol.name, currentOptionId: (detail.values[statusCol.id] as number | null) ?? null, options: statusCol.options.map(({ id, label }) => ({ id, label })) } : null;
  return (
    <Page narrow>
      <EditApplication id={detail.id} title={detail.title} back={{ href: `/tracks/${detail.track.id}`, label: detail.track.name }} archived={detail.archived} columns={detail.columns} values={detail.values}>
        <section aria-labelledby="submissions" className="mb-8">
          <div className="mb-3 flex flex-wrap items-center justify-between gap-3">
            <h2 id="submissions" className="text-lg font-semibold">Submissions</h2>
            <NewSubmission applicationId={detail.id} status={status} />
          </div>
          {subs.length === 0 ? (
            <EmptyState title="Nothing submitted yet" description="Use New submission to record what you sent and when. It is listed here." />
          ) : (
            <SubmissionTimeline key={subs[0].id} items={subs} />
          )}
        </section>
        <dl className="divide-y divide-border rounded-lg border border-border bg-card">
          {detail.columns.map((col) => {
            const value = detail.values[col.id];
            const text = formatCell(col, value);
            const href = col.type === "link" ? safeHref(text) : null;
            const option = col.type === "single_select" ? findOption(col.options, value) : undefined;
            return (
              <div key={col.id} className="grid gap-1 px-3 py-2 sm:grid-cols-[12rem_1fr] sm:gap-4">
                <dt className="text-sm font-medium text-muted-foreground">
                  {col.name}
                  {col.hidden && <span className="ml-2 font-normal">(hidden)</span>}
                </dt>
                <dd className="min-w-0 break-words">
                  {col.type === "checkbox" ? (
                    value === true ? <span className="inline-flex items-center gap-1.5"><CheckIcon aria-hidden className="size-4 text-accent" />Yes</span> : <span className="text-muted-foreground">No</span>
                  ) : href ? (
                    // Never fetched or previewed (NFR-2): the browser only follows it on click.
                    <a href={href} target="_blank" rel="noopener noreferrer" title={href} className="rounded-sm text-accent underline outline-none focus-visible:ring-2 focus-visible:ring-ring">
                      {linkLabel(href)}
                    </a>
                  ) : option ? (
                    <OptionChip option={option} />
                  ) : text ? (
                    text
                  ) : (
                    <span className="text-muted-foreground"><span aria-hidden>—</span><span className="sr-only">Empty</span></span>
                  )}
                </dd>
              </div>
            );
          })}
        </dl>
      </EditApplication>
      <section aria-labelledby="files" className="mt-8">
        <h2 id="files" className="mb-2 text-lg font-semibold">Files</h2>
        <FileUpload applicationId={detail.id} labels={labels} rootSet={root !== null} />
        <FileList files={files} />
      </section>
      {/* Outside EditApplication, so notes stay usable while the Edit form is open. Below Files, so the latest submission stays on screen (AT-12). */}
      <section aria-labelledby="notes" className="mt-8">
        <h2 id="notes" className="mb-2 text-lg font-semibold">Notes</h2>
        <AddNote applicationId={detail.id} />
        {notes.length === 0 ? <EmptyState className="mt-3" title="No notes yet" description="Write a note above. It is listed here with the date and time." /> : <NoteList notes={notes} />}
      </section>
      <ApplicationActions id={detail.id} archived={detail.archived} />
    </Page>
  );
}

export default function ApplicationPage(props: { params: Promise<{ id: string }> }) {
  return (
    <Suspense fallback={<p className="text-muted-foreground">Loading…</p>}>
      <ApplicationView params={props.params} />
    </Suspense>
  );
}
