import { Suspense } from "react";
import { DownloadIcon } from "lucide-react";
import { notFound } from "next/navigation";
import { connection } from "next/server";
import { listTracks } from "@/lib/db/tracks";
import { listApplicationRows } from "@/lib/db/applications";
import { listColumns } from "@/lib/db/columns";
import { TrackViews } from "./track-views";
import { NewApplicationForm } from "./new-application-form";
import { Page, PageHeader } from "@/components/page-header";
import { Button } from "@/components/ui/button";
import { TrackTabs } from "./track-tabs";

// Typed by hand: PageProps<> is generated by `next build`, so a fresh-checkout `tsc` (CI order) would fail.
// Params and DB are request-time under cacheComponents, so everything lives inside the Suspense boundary.
// Unknown ids render the 404 page but with status 200: see the 1.10 report (a real 404 needs a Proxy lookup).
async function TrackView({ params }: { params: Promise<{ id: string }> }) {
  await connection();
  const { id: raw } = await params;
  const id = /^\d+$/.test(raw) ? Number(raw) : NaN;
  const tracks = await listTracks(); // one query serves both the tabs and the current-track lookup
  const track = tracks.find((t) => t.id === id);
  if (!track) notFound();
  const cols = await listColumns(track.id);
  const rows = await listApplicationRows(track.id, cols); // reuse cols: 4 queries, and rows match the headers
  return (
    <Page>
      <PageHeader
        title={track.name}
        description="Export CSV saves every application in this track, archived too, whatever the filters and sort."
        actions={
          <Button asChild variant="outline" size="sm">
            <a href={`/api/tracks/${track.id}/export`} download>
              <DownloadIcon aria-hidden />
              Export CSV
            </a>
          </Button>
        }
      />
      <TrackTabs tracks={tracks} currentId={track.id} />
      <div className="mb-4 rounded-lg border border-border bg-card p-3">
        <NewApplicationForm key={track.id} trackId={track.id} columns={cols} />
      </div>
      <TrackViews trackId={track.id} columns={cols} rows={rows} />
    </Page>
  );
}

export default function TrackPage(props: { params: Promise<{ id: string }> }) {
  return (
    <Suspense fallback={<p className="text-muted-foreground">Loading…</p>}>
      <TrackView params={props.params} />
    </Suspense>
  );
}
